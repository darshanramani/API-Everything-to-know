"""Regenerate js/code-data.js from example/main.py.

Run this after editing example/main.py so the playground shows the same code:
    python build_code_data.py
"""
import json
from pathlib import Path

root = Path(__file__).parent
source = (root / "example" / "main.py").read_text(encoding="utf-8")
out = "/* Generated by build_code_data.py from example/main.py. Do not edit by hand. */\n"
out += "window.APP_CODE = " + json.dumps({"main": source}, ensure_ascii=False) + ";\n"
(root / "js" / "code-data.js").write_text(out, encoding="utf-8")
print("wrote js/code-data.js")
